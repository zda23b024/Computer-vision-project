from sklearn.decomposition import PCA

def pca_plot(X, cluster_ids, title):
    p = PCA(n_components=2, random_state=42)
    Z = p.fit_transform(X)
    plt.figure(figsize=(7,5))
    plt.scatter(Z[:,0], Z[:,1], c=cluster_ids, s=20)
    plt.title(title)
    plt.xlabel("PC1"); plt.ylabel("PC2")
    plt.show()

