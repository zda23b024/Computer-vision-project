"""## 4) SIFT feature extraction (fixed, stable vector length)

Here we build a **Bag of Visual Words (BoVW)** representation:
- Extract SIFT descriptors per image
- Fit MiniBatchKMeans to form a visual vocabulary
- Represent each image as a histogram of visual words
"""

import cv2
from sklearn.cluster import MiniBatchKMeans
from sklearn.preprocessing import normalize

sift = cv2.SIFT_create()

def extract_sift_desc(img_path):
    img = cv2.imread(img_path)
    if img is None:
        return None
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    kp, des = sift.detectAndCompute(gray, None)
    return des  # (n_kp, 128) or None

# 1) collect descriptors
all_des = []
per_img_des = []

for p in all_img_paths:
    des = extract_sift_desc(p)
    per_img_des.append(des)
    if des is not None and len(des) > 0:
        all_des.append(des)

all_des = np.vstack(all_des) if len(all_des) else None
print("Total SIFT descriptors:", None if all_des is None else all_des.shape)

# 2) build vocabulary + histograms
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

vocab_size = 200  # you can tune: 100, 200, 400
if all_des is None:
    raise RuntimeError("No SIFT descriptors found. Check images / OpenCV installation.")

kmeans_vocab = MiniBatchKMeans(n_clusters=vocab_size, random_state=42, batch_size=4096)
kmeans_vocab.fit(all_des)

def bovw_hist(des):
    if des is None or len(des) == 0:
        return np.zeros(vocab_size, dtype=np.float32)
    words = kmeans_vocab.predict(des)
    h, _ = np.histogram(words, bins=np.arange(vocab_size+1))
    return h.astype(np.float32)

X_sift = np.vstack([bovw_hist(d) for d in per_img_des])
X_sift = normalize(X_sift, norm="l1")  # histogram normalization

print("BoVW SIFT feature matrix:", X_sift.shape)

# Optional PCA for compactness
pca_sift = PCA(n_components=50, random_state=42)
X_sift_pca = pca_sift.fit_transform(X_sift)

scaler_sift = StandardScaler()
X_sift_scaled = scaler_sift.fit_transform(X_sift_pca)

print("SIFT after PCA:", X_sift_scaled.shape)

"""## 5) CNN feature extraction (MobileNetV2) + image-path tracking"""

from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.preprocessing.image import img_to_array, load_img
from tensorflow.keras.applications.mobilenet_v2 import preprocess_input
from PIL import UnidentifiedImageError

cnn_model = MobileNetV2(weights="imagenet", include_top=False, pooling="avg")

def load_preprocess(img_path, size=(224,224)):
    try:
        img = load_img(img_path, target_size=size)
        arr = img_to_array(img)
        arr = preprocess_input(arr)
        return arr
    except (UnidentifiedImageError, FileNotFoundError) as e:
        print(f"Warning: Could not load image {img_path} due to: {e}. Skipping this image.")
        return None

batch_size = 32
cnn_features = []
cnn_paths = []
cnn_labels = []

batch_imgs = []
batch_paths = []
batch_labels = []

for p, lab in zip(all_img_paths, all_labels):
    processed_img = load_preprocess(p)
    if processed_img is not None:
        batch_imgs.append(processed_img)
        batch_paths.append(p)
        batch_labels.append(lab)
    if len(batch_imgs) == batch_size:
        feats = cnn_model.predict(np.array(batch_imgs), verbose=0)
        cnn_features.extend(feats)
        cnn_paths.extend(batch_paths)
        cnn_labels.extend(batch_labels)
        batch_imgs, batch_paths, batch_labels = [], [], []

if batch_imgs:
    feats = cnn_model.predict(np.array(batch_imgs), verbose=0)
    cnn_features.extend(feats)
    cnn_paths.extend(batch_paths)
    cnn_labels.extend(batch_labels)

cnn_features = np.array(cnn_features)
print("CNN features:", cnn_features.shape)
print("CNN paths match:", len(cnn_paths) == len(cnn_features))

from sklearn.preprocessing import LabelEncoder
le = LabelEncoder()
y = le.fit_transform(all_labels)  # ground-truth labels (for evaluation only)

# Scale CNN features
from sklearn.preprocessing import StandardScaler
scaler_cnn = StandardScaler()
X_cnn_scaled = scaler_cnn.fit_transform(cnn_features)

print("Label classes:", list(le.classes_))
print("y shape:", y.shape)

"""## 6) Feature fusion (SIFT + CNN)
Early fusion by averaging and weighted scaled SIFT-PCA and scaled CNN features.
"""

# 2) Fusion Strategy 2: Feature Averaging
from sklearn.decomposition import PCA
pca_cnn = PCA(n_components=X_sift_scaled.shape[1], random_state=42)
X_cnn_pca = pca_cnn.fit_transform(X_cnn_scaled)

# Average fusion
X_fused_avg = 0.5 * (X_sift_scaled + X_cnn_pca)
print("Fused features (Averaging):", X_fused_avg.shape)

alpha = 0.8  # Give more weight to CNN features
X_fused_weighted = alpha * X_cnn_pca + (1 - alpha) * X_sift_scaled
print("Fused features (Weighted):", X_fused_weighted.shape)

"""#Alternative methods

1) Power / Gamma Fusion
"""

gamma = 0.8

# Calculate shift value to handle negative numbers in power transformation
min_sift = np.min(X_sift_scaled)
min_cnn = np.min(X_cnn_pca)
min_overall = min(min_sift, min_cnn)
shift_val = 0.0 # Default to 0 if no negative values
if min_overall < 0:
    shift_val = abs(min_overall) + 1e-6 # Add a small epsilon for strict positivity

X_fuse_power = ((X_sift_scaled + shift_val) ** gamma) * ((X_cnn_pca + shift_val) ** (1 - gamma))
print("Power/Gamma fusion:", X_fuse_power.shape)

"""2) Log Fusion"""

# Calculate shift value for log transformation
min_sift = np.min(X_sift_scaled)
min_cnn = np.min(X_cnn_pca)
min_overall = min(min_sift, min_cnn)
shift_val_log = 0.0
if min_overall <= 0:
    shift_val_log = abs(min_overall) + 1e-6 # Add a small epsilon for strict positivity before log1p(1+x) makes it log(1+x_shifted)

X_fuse_log = np.log1p(X_sift_scaled + shift_val_log) + np.log1p(X_cnn_pca + shift_val_log)
print("Log fusion:", X_fuse_log.shape)

"""3.Exponential (Softmax-like) Fusion"""

beta = 2.0
X_fuse_exp = np.exp(beta * (X_sift_scaled + X_cnn_pca))
print("Exponential fusion:", X_fuse_exp.shape)

"""4) Geometric Mean Fusion"""

# Define eps (epsilon) for numerical stability
eps = 1e-9

# Calculate shift value for geometric mean to ensure non-negative inputs
min_sift = np.min(X_sift_scaled)
min_cnn = np.min(X_cnn_pca)
min_overall = min(min_sift, min_cnn)
shift_val_gmean = 0.0
if min_overall <= 0:
    shift_val_gmean = abs(min_overall) + 1e-6 # Add a small epsilon for strict positivity

# Apply shift before multiplication for geometric mean
X_fuse_gmean = np.sqrt((X_sift_scaled + shift_val_gmean) * (X_cnn_pca + shift_val_gmean) + eps)
print("Geometric-mean fusion:", X_fuse_gmean.shape)

"""# Fusion Strategy 3: Weighted Feature Fusion

## 7) Clustering (K-Means) + Evaluation
Metrics:
- **Silhouette score** (unsupervised)
- **ARI / NMI** (uses true labels only for reporting)
"""

from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score, adjusted_rand_score, normalized_mutual_info_score

def cluster_and_report(X, name, n_clusters):
    km = KMeans(n_clusters=n_clusters, random_state=42, n_init="auto")
    pred = km.fit_predict(X)
    sil = silhouette_score(X, pred)
    ari = adjusted_rand_score(y, pred)
    nmi = normalized_mutual_info_score(y, pred)
    print(f"=== {name} ===")
    print("Silhouette:", round(sil, 4))
    print("ARI:", round(ari, 4))
    print("NMI:", round(nmi, 4))
    return pred

k = len(selected_classes)
pred_sift = cluster_and_report(X_sift_scaled, "SIFT (BoVW + PCA)", k)
pred_cnn  = cluster_and_report(X_cnn_scaled,  "CNN (MobileNetV2)", k)
pred_fuse = cluster_and_report(X_fused_weighted,  "Fused (SIFT + CNN)", k)

k = len(selected_classes)
pred_sift = cluster_and_report(X_sift_scaled, "SIFT (BoVW + PCA)", k)
pred_cnn  = cluster_and_report(X_cnn_scaled,  "CNN (MobileNetV2)", k)
pred_fuse = cluster_and_report(X_fused_avg,  "Fused (SIFT + CNN)", k)

k = len(selected_classes)
pred_power = cluster_and_report(X_fuse_power, "Fusion (Power/Gamma)", k)
pred_log   = cluster_and_report(X_fuse_log,   "Fusion (Log)", k)

# Scale X_fuse_exp before clustering to avoid issues with KMeans and silhouette_score
scaler_exp = StandardScaler()
X_fuse_exp_scaled = scaler_exp.fit_transform(X_fuse_exp)
pred_exp   = cluster_and_report(X_fuse_exp_scaled,   "Fusion (Exp) (Scaled)", k)

# Scale X_fuse_gmean before clustering
scaler_gmean = StandardScaler()
X_fuse_gmean_scaled = scaler_gmean.fit_transform(X_fuse_gmean)
pred_gmean = cluster_and_report(X_fuse_gmean_scaled, "Fusion (Geometric Mean) (Scaled)", k)

